// 24-hour historical telemetry points for charts
export const GENERATE_TIME_SERIES = () => {
  const points = [];
  const now = new Date();
  for (let i = 24; i >= 0; i--) {
    const d = new Date(now.getTime() - i * 3600 * 1000);
    const hour = d.getHours().toString().padStart(2, '0') + ':00';
    // Realistic traffic curve: higher in business hours 08:00 - 18:00
    const hourNum = d.getHours();
    const isWorkHours = hourNum >= 8 && hourNum <= 18;
    const baseTraffic = isWorkHours ? 180 : 35;
    const variance = Math.sin(i * 0.5) * 20;

    points.push({
      time: hour,
      rxMbps: Number(Math.max(10, baseTraffic + variance + (i % 3) * 15).toFixed(1)),
      txMbps: Number(Math.max(8, (baseTraffic * 0.65) + variance * 0.8 + (i % 2) * 10).toFixed(1)),
      avgLatencyMs: Number((1.2 + (isWorkHours ? 0.6 : 0.1) + Math.sin(i) * 0.2).toFixed(2)),
      packetLoss: hourNum === 5 ? 0.4 : 0.0,
      cpuPercent: Number((12 + (isWorkHours ? 6 : 2) + Math.cos(i) * 2).toFixed(1)),
      ramPercent: 26.2
    });
  }
  return points;
};
